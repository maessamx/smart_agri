import pandas as pd
import streamlit as st
from src.datasets.irrigation.model import predict as predict_irrigation, train_model as train_irrigation_model
from src.ui.component import initialize_page, hero, section_title, callout

st.set_page_config(page_title='Irrigation Control | Smart Agri Egypt', page_icon='💧', layout='wide')
initialize_page()
hero('Irrigation Control', 'Enter current farm conditions to obtain an irrigation decision generated by the trained classification model.')

model, training_data, model_metrics = train_irrigation_model()
left, right = st.columns([1, 1])
with left:
    crop = st.selectbox('Crop', sorted(training_data['crop ID'].unique()))
    soil = st.selectbox('Soil Type', sorted(training_data['soil_type'].unique()))
    stage = st.selectbox('Growth Stage', list(training_data['Seedling Stage'].unique()))
    moisture = st.slider('Moisture Index (MOI)', 0, 100, 35)
    temperature = st.slider('Temperature (°C)', 0, 55, 30)
    humidity = st.slider('Humidity (%)', 0, 100, 55)
    run_prediction = st.button('Evaluate Irrigation Requirement')

with right:
    st.metric('Validation Accuracy', f"{model_metrics['accuracy']:.1%}")
    st.markdown("<div class='card'><h3>Model Input</h3><p class='muted'>The model uses crop type, soil type, growth stage, moisture index, temperature, and humidity. The model is trained from <code>data/irrigation/irrigation_training_data.csv</code>.</p></div>", unsafe_allow_html=True)

if run_prediction:
    input_data = pd.DataFrame([{
        'crop ID': crop,
        'soil_type': soil,
        'Seedling Stage': stage,
        'MOI': moisture,
        'temp': temperature,
        'humidity': humidity
    }])
    prediction, confidence = predict_irrigation(input_data)
    labels = {
        0: ('No Irrigation Required', 'Predicted Class 0: current conditions indicate that irrigation is not required at this time.'),
        1: ('Medium Irrigation Required', 'Predicted Class 1: apply a moderate irrigation cycle, then recheck soil conditions.'),
        2: ('High Irrigation Required', 'Predicted Class 2: the field requires a higher irrigation level. Confirm the reading before operating the irrigation system.')
    }
    title, message = labels.get(prediction, ('Model Result', 'No interpretation is available for this class.'))
    section_title('Irrigation Decision')
    if prediction == 1:
        st.warning(f'{title} — {message}')
    elif prediction == 2:
        st.error(f'{title} — {message}')
    else:
        st.success(f'{title} — {message}')
    a, b, c = st.columns(3)
    a.metric('Predicted Class', prediction)
    b.metric('Model Confidence', f'{confidence:.1%}')
    c.metric('Current MOI', moisture)
    callout('This is a decision-support output. Field verification and irrigation safety rules are required before opening a pump or valve.')
